# Static context (loaded once per process)
# ═════════════════════════════════════════════════════════════════════════════
class Ctx:
    def __init__(self, data_dir: Path = DATA_DIR):
        self.world: World = build_world(seed=SEED)
        self.posts = self.world.posts.set_index("id")
        self.skus = self.world.skus.set_index("sku")
        self.anchors = assign_anchors(self.world.posts).set_index("post_id")["anchor_name"]
        # AWS targets: carry the latest committed winter-year forward
        aws = pd.read_parquet(data_dir / "aws_plan.parquet")
        latest = aws["winter_year"].max()
        a = aws[aws["winter_year"] == latest]
        self.aws_target = a.set_index(["post_id", "sku"])["aws_target_qty"].to_dict()
        self.rate = a.set_index(["post_id", "sku"])["winter_daily_rate_mean"].to_dict()
        self.plan_days = a.set_index(["post_id", "sku"])["planning_days"].to_dict()
        # vehicle persistent identities — replayed exactly (first draws on the
        # seed-42 stream, identical to what the batch consumed)
        vr = np.random.default_rng(SEED)
        self.band_mix = draw_vehicle_band_mixes(vr, self.world.vehicles, self.world.posts)
        self.duty = draw_duty_intensities(vr, self.world.vehicles)
        self.vehicles = self.world.vehicles.set_index("vehicle_id")
        self.all_passes = list(PASSES.keys())
        # pass -> config
        self.pass_cfg = PASSES
        # rep-post map for stochastic closures (mirrors disruption.py)
        self.rep_posts = {
            "rear_admin": ["P001", "P002"], "nubra_axis": ["P017"],
            "pangong_axis": ["P003", "P008", "P018"],
            "chushul_demchok": ["P005", "P020", "P022"],
            "hot_springs_galwan": ["P027", "P028", "P030"],
        }


# ═════════════════════════════════════════════════════════════════════════════
# State initialisation from the canonical boundary
# ═════════════════════════════════════════════════════════════════════════════
def init_state(ctx: Ctx, data_dir: Path = DATA_DIR) -> WorldState:
    st = WorldState()
    st.sim_date = END_DATE

    # stock: last committed day
    sd = pd.read_parquet(data_dir / "stock_daily.parquet",
                          columns=["post_id", "sku", "date", "closing_stock"])
    sd["date"] = pd.to_datetime(sd["date"]).dt.date
    last = sd[sd["date"] == END_DATE]
    for _, r in last.iterrows():
        st.stock[(r["post_id"], r["sku"])] = float(r["closing_stock"])

    # AWS: new-year remaining initialises on Jan 1 inside the step
    st.aws_year = END_DATE.year
    st.aws_remaining = {}

    # weather noise per post
    st.noise_state = {pid: 0.0 for pid in ctx.posts.index}

    # tempo: last committed value
    tempo = pd.read_parquet(data_dir / "tempo_daily.parquet")
    tempo["date"] = pd.to_datetime(tempo["date"]).dt.date
    st.tempo = str(tempo.sort_values("date").iloc[-1]["tempo_level"])

    # closures spanning the boundary + winter-2024-25 already sampled in batch
    cl = pd.read_parquet(data_dir / "pass_closures.parquet")
    cl["start_date"] = pd.to_datetime(cl["start_date"]).dt.date
    cl["end_date"] = pd.to_datetime(cl["end_date"]).dt.date
    # The batch CLIPS closures to the simulation range, so a winter closure
    # in progress at END_DATE is recorded as "ending" on END_DATE. Reconstruct
    # the true end from the pass's climatological duration prior (BRO reopen
    # dates cluster around the mean — Zoji La reopens in spring, not Jan 1).
    spanning = cl[cl["end_date"] >= END_DATE]
    for _, c in spanning.iterrows():
        end = c["end_date"]
        if end == END_DATE and c["closure_type"] == "seasonal":
            pcfg = ctx.pass_cfg.get(c["pass_name"], {})
            dur = int(pcfg.get("closure_duration_days_mean", 0))
            if dur > 0:
                end = c["start_date"] + timedelta(days=dur)
        if end > END_DATE:
            st.active_closures.append({"pass_name": c["pass_name"],
                                        "end_date": end.isoformat(),
                                        "closure_type": str(c["closure_type"])})
    # Winter season already covered by batch sampling: 2024-25 for seasonal
    # passes (their closure windows were drawn in the batch run, including
    # the spanning ones we just carried).
    for pname, pcfg in ctx.pass_cfg.items():
        if pcfg.get("closure_regime") == "seasonal":
            st.sampled_winters[pname] = [END_DATE.year]  # winter 2024-25 done
    st.wd_sampled_seasons = [END_DATE.year]              # WD winter 2024-25:
    # batch sampled its events; any extending past Dec 31 are rare and short
    # (≤4 days) — dropped, documented.

    # vehicles: memoryless restart; carry only in-repair-at-boundary
    ev = pd.read_parquet(data_dir / "vehicle_events.parquet")
    ev["return_date"] = pd.to_datetime(ev["return_date"]).dt.date
    in_repair = ev[ev["return_date"] > END_DATE].set_index("vehicle_id")["return_date"]
    rt = np.random.default_rng([SEED, END_DATE.toordinal(), _DOMAIN["vehicle"], 77])
    for vid in ctx.vehicles.index:
        st.veh[vid] = {
            "cum": 0.0,
            "thr": float(rt.exponential(1.0)),
            "repair_until": in_repair[vid].isoformat() if vid in in_repair.index else None,
        }
    return st


# ═════════════════════════════════════════════════════════════════════════════
# One-day step
# ═════════════════════════════════════════════════════════════════════════════
def advance_one_day(ctx: Ctx, st: WorldState) -> dict:
    """Advance the world to st.sim_date + 1. Returns {table: [rows]} for the
    day. Mutates st. Deterministic for (SEED, date)."""
    d = st.sim_date + timedelta(days=1)
    out = {"weather_daily": [], "pass_status_daily": [], "tempo_daily": [],
           "stock_daily": [], "vehicle_events": [], "consumption_daily": []}
    winter = d.month in (11, 12, 1, 2, 3)

    # ── 1. tempo (Markov, day-seeded) ────────────────────────────────────────
    rt = _rng("tempo", d)
    probs = TEMPO_TRANSITION_PROBS_DAILY[st.tempo]
    st.tempo = str(rt.choice(TEMPO_LEVELS, p=[probs[s] for s in TEMPO_LEVELS]))
    out["tempo_daily"].append({"date": d, "tempo_level": st.tempo,
                                "generator": GENERATOR_TAG})

    # ── 2. WD events: sample each winter season once (year-seeded) ──────────
    if d.month == 12 and d.day == 1 and d.year not in st.wd_sampled_seasons:
        ry = _rng_year("wd", d.year)
        n_ev = int(ry.poisson(WD_EVENTS_PER_WINTER_LAMBDA))
        season_days = (date(d.year + 1, 3, 31) - d).days
        for _ in range(n_ev):
            es = d + timedelta(days=int(ry.integers(0, season_days)))
            st.wd_future.append({
                "start": es.isoformat(),
                "end": (es + timedelta(days=int(ry.integers(
                    WD_EVENT_DURATION_DAYS[0], WD_EVENT_DURATION_DAYS[1] + 1)))).isoformat(),
                "precip_mult": float(ry.uniform(*WD_EVENT_PRECIP_MULT)),
                "temp_drop": float(ry.uniform(*WD_EVENT_TEMP_DROP_C)),
            })
        st.wd_sampled_seasons.append(d.year)
    # activate / expire
    st.wd_active = [e for e in (st.wd_active + [e for e in st.wd_future
                                                 if e["start"] == d.isoformat()])
                    if e["end"] >= d.isoformat()]
    st.wd_future = [e for e in st.wd_future if e["start"] > d.isoformat()]
    wd_intensity = {"Drass": 1.0, "Tangtse": 0.55, "Leh": 0.25}

    # ── 3. weather per post (AR(1) carried, day-seeded shocks) ──────────────
    rw = _rng("weather", d)
    t_mean_by_post: Dict[str, float] = {}
    snow_by_post: Dict[str, float] = {}
    sigma = DAILY_TEMP_NOISE_SIGMA + (DAILY_TEMP_NOISE_WINTER_BOOST if winter else 0.0)
    for pid in ctx.posts.index:
        post = ctx.posts.loc[pid]
        aname = ctx.anchors[pid]
        anchor = get_anchor(aname)
        t_max_c, t_min_c, precip_expected = climatological_day(anchor, d, post["elev_m"])
        shock = rw.normal(0, sigma)
        ns = (DAILY_TEMP_PERSISTENCE * st.noise_state.get(pid, 0.0)
              + np.sqrt(1 - DAILY_TEMP_PERSISTENCE ** 2) * shock)
        st.noise_state[pid] = float(ns)
        t_max, t_min = t_max_c + ns, t_min_c + ns
        wet_p = min(0.50, precip_expected / 2.5)
        precip = 0.0
        if wet_p > 0 and rw.random() < wet_p:
            precip = float(rw.exponential(scale=precip_expected / wet_p))
        is_wd = False
        for e in st.wd_active:
            inten = wd_intensity.get(aname, 0.5)
            pulse = float(rw.uniform(1.5, 7.0)) * (1.0 + (e["precip_mult"] - 1.0) * inten) / 2.5
            precip = max(precip, pulse)
            t_max -= e["temp_drop"] * inten
            t_min -= e["temp_drop"] * inten
            is_wd = True
        t_mean = (t_max + t_min) / 2.0
        is_snow = bool(t_mean < 1.0 and precip > 0.5)
        t_mean_by_post[pid] = t_mean
        snow_by_post[pid] = precip * (1.0 if is_snow else 0.0)
        out["weather_daily"].append({
            "post_id": pid, "date": d, "t_max_c": round(t_max, 2),
            "t_min_c": round(t_min, 2), "t_mean_c": round(t_mean, 2),
            "precip_mm": round(precip, 2), "is_snow": is_snow,
            "is_wd_active": is_wd, "anchor_name": aname,
            "generator": GENERATOR_TAG})

    # ── 4. pass status (seasonal year-seeded; stochastic day-seeded) ────────
    rc = _rng("closure", d)
    # 4a. sample NEXT winter's seasonal closures once we enter October
    for pname, pcfg in ctx.pass_cfg.items():
        if pcfg.get("closure_regime") != "seasonal":
            continue
        wy = d.year if d.month >= 10 else d.year - 1
        if d.month >= 10 and wy not in st.sampled_winters.get(pname, []):
            ry = _rng_year("closure", wy * 100 + hash(pname) % 97)
            jitter = ry.normal(0, pcfg["closure_start_doy_sigma"])
            base = date(wy, 1, 1) + timedelta(
                days=int(pcfg["closure_start_doy_mean"] + jitter) - 1)
            dur = int(np.clip(ry.normal(pcfg["closure_duration_days_mean"],
                                         pcfg["closure_duration_days_sigma"]),
                               pcfg["min_closure_days"], pcfg["max_closure_days"]))
            st.future_closures.append({
                "pass_name": pname, "start": base.isoformat(),
                "end": (base + timedelta(days=dur)).isoformat(),
                "closure_type": "seasonal"})
            st.sampled_winters.setdefault(pname, []).append(wy)
    # activate scheduled
    for fc in [f for f in st.future_closures if f["start"] == d.isoformat()]:
        st.active_closures.append({"pass_name": fc["pass_name"],
                                    "end_date": fc["end"],
                                    "closure_type": fc["closure_type"]})
    st.future_closures = [f for f in st.future_closures if f["start"] > d.isoformat()]
    # expire
    st.active_closures = [c for c in st.active_closures
                           if c["end_date"] >= d.isoformat()]
    closed_today = {c["pass_name"] for c in st.active_closures}
    # 4b. stochastic + interim regimes — daily Bernoulli with snow boost
    for pname, pcfg in ctx.pass_cfg.items():
        if pname in closed_today:
            continue
        regime = pcfg.get("closure_regime")
        if regime == "stochastic":
            rep = ctx.rep_posts.get(pcfg["served_posts_classification"], ["P001"])
            sev = max(snow_by_post.get(p, 0.0) for p in rep)
            p_base = (pcfg["winter_closure_prob_per_day"]
                      if d.month in (11, 12, 1, 2, 3, 4)
                      else pcfg["summer_closure_prob_per_day"])
            p = min(0.95, p_base * SNOW_EVENT_CLOSURE_BOOST) \
                if sev >= SNOW_EVENT_THRESHOLD_MM else p_base
            if rc.random() < p:
                dur = int(rc.integers(*pcfg["closure_duration"]))
                st.active_closures.append({
                    "pass_name": pname,
                    "end_date": (d + timedelta(days=dur)).isoformat(),
                    "closure_type": "stochastic_snow" if sev >= SNOW_EVENT_THRESHOLD_MM
                                    else "stochastic_routine"})
                closed_today.add(pname)
        elif regime == "seasonal":
            ip = pcfg.get("interim_closure_prob_per_day", 0.0)
            if ip > 0 and rc.random() < ip:
                dur = int(rc.integers(*pcfg["interim_closure_duration"]))
                st.active_closures.append({
                    "pass_name": pname,
                    "end_date": (d + timedelta(days=dur)).isoformat(),
                    "closure_type": "interim"})
                closed_today.add(pname)
    for pname in ctx.all_passes:
        out["pass_status_daily"].append({"pass_name": pname, "date": d,
                                          "is_open": pname not in closed_today,
                                          "generator": GENERATOR_TAG})

    # ── 5. isolation per post (same truth consumption + stock both see) ─────
    ps_df = pd.DataFrame(out["pass_status_daily"])
    iso_df = compute_isolation_per_post_day(ctx.world, ps_df)
    iso = iso_df.set_index("post_id")["is_isolated"].to_dict()

    # ── 6. consumption + stock per (post, SKU) ───────────────────────────────
    rcons = _rng("consumption", d)
    rstock = _rng("stock", d)
    # AWS year rollover
    if d.month == 1 and d.day == 1:
        st.aws_year = d.year
        st.aws_remaining = {k: float(v) for k, v in ctx.aws_target.items()}
    if not st.aws_remaining and d.month in AWS_SEASON_MONTHS:
        st.aws_remaining = {k: float(v) for k, v in ctx.aws_target.items()}
    is_aws_day = d.month in AWS_SEASON_MONTHS or (d.month == 10 and d.day <= 10)
    if is_aws_day:
        # crude remaining-open-day estimate without hindsight: calendar days
        # left in the AWS window this year
        rem_days = 0
        for m in AWS_SEASON_MONTHS:
            if m > d.month:
                rem_days += _days_in_month(d.year, m)
            elif m == d.month:
                rem_days += _days_in_month(d.year, m) - d.day + 1
        rem_days += 10 if d.month <= 10 else 0
        rem_days = max(rem_days, 1)

    for pid in ctx.posts.index:
        post = ctx.posts.loc[pid].to_dict()
        post["band"] = ctx.posts.loc[pid]["band"]
        is_iso = bool(iso.get(pid, False))
        t_mean = t_mean_by_post[pid]
        for sku_id in ctx.skus.index:
            sku = ctx.skus.loc[sku_id].to_dict()
            sku["sku"] = sku_id
            key = (pid, sku_id)
            if key not in st.stock:
                continue
            perishable = _is_perishable(int(sku["shelf_life_days"]))
            tier = int(sku["tier"])

            nominal = draw_consumption(rcons, sku, post, t_mean, st.tempo, is_iso)
            # perishable substitution (isolation-gated simple rule)
            consumed = nominal
            if perishable and is_iso:
                sub = PERISHABLE_SUBSTITUTE_MAP.get(sku_id)
                consumed = 0.0
                if sub and (pid, sub) in st.stock:
                    st.setdefault_delta = None  # no-op marker
                    # add displaced demand onto substitute by direct draw-down
                    # handled below via demand_delta dict
            out["consumption_daily"].append({
                "post_id": pid, "sku": sku_id, "date": d,
                "qty_consumed": round(nominal, 3), "tempo": st.tempo,
                "is_isolated": bool(is_iso), "t_mean_c": round(t_mean, 2),
                "generator": GENERATOR_TAG})

            opening = st.stock[key]
            # AWS receipt
            aws_rx = 0.0
            if is_aws_day and not is_iso and st.aws_remaining.get(key, 0.0) > 0:
                aws_rx = min(st.aws_remaining[key] / rem_days, st.aws_remaining[key])
                st.aws_remaining[key] -= aws_rx
            # routine arrivals
            routine_rx = 0.0
            keep = []
            for arr, qty in st.pending.get(key, []):
                if arr == d.isoformat():
                    routine_rx += qty
                elif arr > d.isoformat():
                    keep.append((arr, qty))
            st.pending[key] = keep
            # perishable demand displacement: fresh→substitute while isolated
            delta = 0.0
            if is_iso:
                for fresh, sub in PERISHABLE_SUBSTITUTE_MAP.items():
                    if sub == sku_id and (pid, fresh) in st.stock:
                        f_sku = ctx.skus.loc[fresh].to_dict(); f_sku["sku"] = fresh
                        delta += draw_consumption(
                            _rng("consumption", d), f_sku, post, t_mean,
                            st.tempo, is_iso) * 0.8   # 80% substitution take-up
            consumed = max(0.0, (0.0 if (perishable and is_iso) else nominal) + delta)
            spoil = opening * SPOILAGE_DAILY_FRACTION_PERISHABLE if perishable else 0.0
            available = opening + aws_rx + routine_rx - spoil
            if available >= consumed:
                closing, unmet = available - consumed, 0.0
            else:
                closing, unmet = 0.0, consumed - available
            rate = ctx.rate.get(key, 0.0) or max(consumed, 1e-6)
            doc = closing / rate
            thresh = STOCKOUT_RATIONING_THRESHOLD_DAYS[tier]
            status = ("stockout" if (unmet > 0 or closing <= 0)
                      else "rationing" if doc < thresh else "ok")
            # routine convoy dispatch
            plan_days = ctx.plan_days.get(key, ROUTINE_RECEIPT_REFILL_TO_COVERAGE_DAYS)
            is_pol = str(sku_id).startswith("POL")
            min_gap = POL_CONVOY_MIN_GAP_DAYS if is_pol else ROUTINE_CONVOY_MIN_GAP_DAYS
            lc = st.last_convoy.get(key)
            since = (d - date.fromisoformat(lc)).days if lc else 9999
            if (not is_iso and not st.pending.get(key) and rate > 0
                    and since >= min_gap
                    and (plan_days - doc) > ROUTINE_CONVOY_DISPATCH_GAP_DAYS):
                refill = max(0.0, plan_days * rate - closing)
                if is_pol:
                    refill = min(refill, POL_CONVOY_MAX_REFILL_COVERAGE_DAYS * rate)
                if refill > 0:
                    lat = int(rstock.integers(ROUTINE_RECEIPT_CONVOY_LATENCY_DAYS[0],
                                               ROUTINE_RECEIPT_CONVOY_LATENCY_DAYS[1] + 1))
                    st.pending.setdefault(key, []).append(
                        ((d + timedelta(days=lat)).isoformat(), float(refill)))
                    st.last_convoy[key] = d.isoformat()
            st.stock[key] = float(closing)
            out["stock_daily"].append({
                "post_id": pid, "sku": sku_id, "date": d,
                "opening_stock": round(opening, 3), "aws_receipt": round(aws_rx, 3),
                "routine_receipt": round(routine_rx, 3),
                "nominal_consumption": round(nominal, 3),
                "consumption": round(consumed, 3), "spoilage": round(spoil, 3),
                "unmet_demand": round(unmet, 3), "closing_stock": round(closing, 3),
                "days_of_cover": round(doc, 2), "status": status,
                "generator": GENERATOR_TAG})

    # ── 7. vehicles (memoryless hazard, day-seeded) ──────────────────────────
    rv = _rng("vehicle", d)
    pass_open_today = {p: (p not in closed_today) for p in ctx.all_passes}
    any_closed = any(not v for v in pass_open_today.values())
    mission_p = (MISSIONS_PER_MONTH_WINTER if winter else MISSIONS_PER_MONTH_OPEN) / 30.0
    lookup = {(p, d): pass_open_today[p] for p in ctx.all_passes}
    for vid in ctx.vehicles.index:
        v = st.veh[vid]
        if v["repair_until"]:
            if d.isoformat() >= v["repair_until"]:
                v["repair_until"] = None
            else:
                continue
        if rv.random() < mission_p:
            scale = float(ctx.vehicles.loc[vid]["weibull_scale_days"])
            v["cum"] += ctx.duty[vid] * daily_hazard_increment(
                rv, d, lookup, ctx.all_passes, scale, ctx.band_mix[vid])
            if v["cum"] >= v["thr"]:
                if rv.random() < DEADLINE_REQUIRES_DEPOT_PROB:
                    rd = int(rv.integers(*REPAIR_TIME_DEPOT_DAYS)); loc = "depot"
                else:
                    rd = int(rv.integers(*REPAIR_TIME_FIELD_DAYS)); loc = "field"
                ret = d + timedelta(days=rd)
                out["vehicle_events"].append({
                    "vehicle_id": vid,
                    "vehicle_class": ctx.vehicles.loc[vid]["vehicle_class"],
                    "deadline_date": d, "return_date": ret, "repair_days": rd,
                    "repair_location": loc, "winter_flag": winter,
                    "generator": GENERATOR_TAG})
                v["repair_until"] = ret.isoformat()
                v["cum"] = 0.0
                v["thr"] = float(sample_event_threshold(rv)) * 0.85

    st.sim_date = d
    return out


