"""
Project Bastion — Stage 2: Incremental World Advancement (#8, v1.0)

Refactors the world from batch-only to LIVE: `advance_one_day(state)` steps
the synthetic world one day past the canonical horizon (2024-12-31), so the
daily tick re-plans a moving world instead of a frozen snapshot.

DESIGN — canonical history + deterministic continuation
────────────────────────────────────────────────────────
The committed seed-42 world through END_DATE stays byte-identical — every
published metric stands. Days AFTER it are generated by this stepper using
the SAME per-day physics functions the batch generator uses
(draw_consumption, climatological_day, daily_hazard_increment, the stock
accounting identity, the closure regimes), with DAY-SEEDED RNG:

    rng(domain, date) = default_rng([42, date.toordinal(), domain_id])

Day-seeding gives three properties batch streams can't:
  • deterministic     — advancing to 2025-03-01 always yields the same world
  • restart-safe      — kill the process, re-init, fast-forward: identical
  • order-independent — 45 days + 45 days ≡ 90 days in one call

BOUNDARY STATE (what carries across 2024-12-31)
  • closing stock per (post, SKU)         — from committed stock_daily
  • active pass closures                  — Zoji La's winter closure SPANS the
    boundary (closes ~Dec 23, reopens spring); read from pass_closures and
    carried. Winter 2024-25 closures are NOT resampled. Fresh sampling starts
    with winter 2025-26.
  • brigade tempo                         — last committed tempo state
  • vehicles in repair at the boundary    — events with return_date > END_DATE
  • vehicle hazard clocks                 — fresh Exp(1) thresholds, cum=0.
    The hazard process is MEMORYLESS (Exp(1) threshold, linear accumulation),
    so this is distributionally exact, not an approximation.
  • per-vehicle band mixes / duty factors — replayed exactly: they are the
    first draws on the seed-42 stream (draw_vehicle_band_mixes then
    draw_duty_intensities), so the continuation uses the SAME persistent
    vehicle identities the canonical history used.

DOCUMENTED SIMPLIFICATIONS (continuation only, all SYNTHETIC-INFERRED)
  • AWS targets for years > 2024 carry the 2024 targets forward (stocking
    norms are sticky year-to-year; no public per-year deltas to anchor).
  • AWS pacing uses remaining-candidate-day count without isolation
    foreknowledge (the batch precounts open days with full hindsight; a
    live system cannot — this is MORE realistic, not less).
  • Routine convoys in transit at the boundary are dropped (their latency
    is 1-3 days; effect is a one-time ripple in the first continuation week).
  • Perishable substitution uses the isolation-gated rule (isolated ⇒ fresh
    demand routes to substitute) without the batch's adaptation decay curve.
  • Weather AR(1) noise state initialises at 0 (one-day transient).

OUTPUTS
  state.json + stock_state.parquet in WORLD_STATE_DIR after each advance;
  per-day rows appended to live_*.parquet; `materialize_live_data()` builds
  a complete Stage-3-ready data dir (base ∪ continuation) so downstream
  stages run unchanged with BASTION_DATA_DIR pointed at it.

Every continuation row carries provenance: generator="advance_v1",
day_seed=[42, ordinal, domain].
"""

