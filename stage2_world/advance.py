# Orchestration: advance N days, persist live tables, materialize for Stage 3
# ═════════════════════════════════════════════════════════════════════════════
_LIVE_TABLES = ["weather_daily", "pass_status_daily", "tempo_daily",
                "stock_daily", "vehicle_events", "consumption_daily"]


def advance_to(target: date, state_dir: Path = WORLD_STATE_DIR,
               data_dir: Path = DATA_DIR, verbose: bool = True) -> WorldState:
    """Advance the world state to `target` (inclusive). Initialises state at
    the canonical boundary if none exists. Appends per-day rows to
    live_<table>.parquet under state_dir."""
    ctx = Ctx(data_dir)
    if (state_dir / "state.json").exists():
        st = WorldState.load(state_dir)
    else:
        st = init_state(ctx, data_dir)
        if verbose:
            print(f"[advance] initialised state at canonical boundary {st.sim_date}")
    if target <= st.sim_date:
        if verbose:
            print(f"[advance] already at {st.sim_date} ≥ {target} — nothing to do")
        return st

    buf = {t: [] for t in _LIVE_TABLES}
    n = 0
    while st.sim_date < target:
        day_rows = advance_one_day(ctx, st)
        for t in _LIVE_TABLES:
            buf[t].extend(day_rows[t])
        n += 1
    # append to live parquets
    state_dir.mkdir(exist_ok=True, parents=True)
    for t in _LIVE_TABLES:
        if not buf[t]:
            continue
        new = pd.DataFrame(buf[t])
        live_p = state_dir / f"live_{t}.parquet"
        if live_p.exists():
            old = pd.read_parquet(live_p)
            # idempotency: drop any overlap (re-advance after restart)
            new = pd.concat([old, new], ignore_index=True)
            sub = [c for c in ("post_id", "sku", "pass_name", "vehicle_id", "date")
                   if c in new.columns]
            new = new.drop_duplicates(subset=sub, keep="last")
        new.to_parquet(live_p, index=False)
    st.save(state_dir)
    if verbose:
        print(f"[advance] advanced {n} day(s) → sim_date {st.sim_date}")
    return st


def materialize_live_data(out_dir: Path, state_dir: Path = WORLD_STATE_DIR,
                           data_dir: Path = DATA_DIR) -> Path:
    """Build a complete Stage-3-ready data dir: canonical base ∪ continuation.
    Point BASTION_DATA_DIR here and Stages 3-4 run unchanged."""
    out_dir.mkdir(exist_ok=True, parents=True)
    static = ["posts", "routes", "skus", "vehicles", "post_distances", "aws_plan",
              "pass_closures", "wd_events"]
    for t in static:
        src = data_dir / f"{t}.parquet"
        if src.exists():
            shutil.copy2(src, out_dir / f"{t}.parquet")
    for t in _LIVE_TABLES:
        base_p = data_dir / f"{t}.parquet"
        live_p = state_dir / f"live_{t}.parquet"
        frames = []
        if base_p.exists():
            frames.append(pd.read_parquet(base_p))
        if live_p.exists():
            live = pd.read_parquet(live_p)
            live = live.drop(columns=["generator"], errors="ignore")
            frames.append(live)
        if frames:
            allf = pd.concat(frames, ignore_index=True)
            allf.to_parquet(out_dir / f"{t}.parquet", index=False)
    return out_dir


if __name__ == "__main__":
    import argparse
    ap = argparse.ArgumentParser(description="Advance the synthetic world")
    ap.add_argument("--to", type=str, required=True, help="target date YYYY-MM-DD")
    ap.add_argument("--materialize", type=str, default=None,
                    help="optional dir to materialize a Stage-3-ready dataset")
    args = ap.parse_args()
    st = advance_to(date.fromisoformat(args.to))
    if args.materialize:
        p = materialize_live_data(Path(args.materialize))
        print(f"[advance] materialized live dataset → {p}")
